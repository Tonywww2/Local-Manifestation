package content

import (
	"encoding/json"
	"fmt"
	"hsmultiplayer/internal/native"
	"hsmultiplayer/pkg/mods"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"runtime"
	"strings"
)

var identifier = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

// BuildNative is an explicit developer action. Archives are compiled separately;
// the host is statically relinked, reusing Go's compiler cache for unchanged code.
// Build inputs live in a separate workspace; original source is never changed.
func BuildNative(sourceRoot, store, lockPath, out string) error {
	root, err := filepath.Abs(sourceRoot)
	if err != nil {
		return err
	}
	lock, err := LoadLock(lockPath)
	if err != nil {
		return err
	}
	layers, err := sources(store, lock)
	if err != nil {
		return err
	}
	build := filepath.Join(root, ".cache", "native-build")
	if err = os.MkdirAll(build, 0755); err != nil {
		return err
	}
	modData, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		return fmt.Errorf("bundled host/SDK source required: %w", err)
	}
	goExecutable, err := nativeToolchain(root, string(modData))
	if err != nil {
		return err
	}
	workspace, err := os.MkdirTemp(build, "host-*")
	if err != nil {
		return err
	}
	if err = copyHostSource(root, workspace); err != nil {
		return err
	}
	registrations := ""
	imports := ""
	nativeCount := 0
	for _, layer := range layers {
		entry := layer.manifest.Go
		if entry == nil {
			continue
		}
		hash, err := CodeDigest(layer.files)
		if err != nil {
			return err
		}
		dir := filepath.Join(build, "sources", hash)
		if err = os.MkdirAll(dir, 0755); err != nil {
			return err
		}
		err = fs.WalkDir(layer.files, ".", func(path string, e fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if e.IsDir() {
				return nil
			}
			target := filepath.Join(dir, filepath.FromSlash(path))
			relative, err := filepath.Rel(dir, target)
			if err != nil || relative == ".." || strings.HasPrefix(relative, ".."+string(filepath.Separator)) {
				return fmt.Errorf("unsafe native source path")
			}
			data, err := fs.ReadFile(layer.files, path)
			if err != nil {
				return err
			}
			return atomicFile(target, data)
		})
		if err != nil {
			return err
		}
		moduleData, err := os.ReadFile(filepath.Join(dir, "go.mod"))
		if err != nil {
			return fmt.Errorf("Go package requires go.mod")
		}
		module := ""
		for _, line := range strings.Split(string(moduleData), "\n") {
			fields := strings.Fields(line)
			if len(fields) == 2 && fields[0] == "module" {
				module = strings.Trim(fields[1], "\"")
				break
			}
		}
		if module == "" || module == "hsmultiplayer" || strings.ContainsAny(module, " \t\r\n\"`") {
			return fmt.Errorf("invalid native module path")
		}
		if entry.Package != module && !strings.HasPrefix(entry.Package, module+"/") {
			return fmt.Errorf("entry package must belong to its module")
		}
		for _, function := range []string{entry.Shared, entry.Server, entry.Client} {
			if function != "" && !identifier.MatchString(function) {
				return fmt.Errorf("invalid native entry function")
			}
		}
		version := "v0.0.0"
		if suffix := regexp.MustCompile(`/v([2-9][0-9]*)$`).FindStringSubmatch(module); len(suffix) == 2 {
			version = "v" + suffix[1] + ".0.0"
		}
		modData = append(modData, []byte(fmt.Sprintf("\nrequire %s %s\nreplace %s => %q\n", module, version, module, filepath.ToSlash(dir)))...)
		alias := fmt.Sprintf("module%d", nativeCount)
		imports += fmt.Sprintf("%s %q\n", alias, entry.Package)
		registrations += fmt.Sprintf("Add(Entry{ID:%q,Version:%q,CodeSHA256:%q", layer.manifest.ID, layer.manifest.Version, hash)
		for _, side := range []struct{ name, value string }{{"Shared", entry.Shared}, {"Server", entry.Server}, {"Client", entry.Client}} {
			if side.value != "" {
				registrations += fmt.Sprintf(",%s:%s.%s", side.name, alias, side.value)
			}
		}
		registrations += "})\n"
		nativeCount++
	}
	modFile := filepath.Join(workspace, "host.mod")
	if err = atomicFile(modFile, modData); err != nil {
		return err
	}
	sum, err := os.ReadFile(filepath.Join(root, "go.sum"))
	if err != nil {
		return err
	}
	if err = atomicFile(filepath.Join(workspace, "host.sum"), sum); err != nil {
		return err
	}
	generated := filepath.Join(workspace, "internal", "native", "generated.go")
	code := "// Code generated by modtool build; DO NOT EDIT.\npackage native\n"
	if imports != "" {
		code += "import (\n" + imports + ")\n"
	}
	code += "func init(){\n" + registrations + "}\n"
	if err = atomicFile(generated, []byte(code)); err != nil {
		return err
	}
	run := func(args ...string) error {
		command := exec.Command(goExecutable, args...)
		command.Dir = workspace
		for _, entry := range os.Environ() {
			key, _, _ := strings.Cut(entry, "=")
			if key != "CGO_ENABLED" && key != "GOOS" && key != "GOARCH" {
				command.Env = append(command.Env, entry)
			}
		}
		command.Env = append(command.Env, "CGO_ENABLED=0", "GOOS="+runtime.GOOS, "GOARCH="+runtime.GOARCH)
		data, err := command.CombinedOutput()
		if err != nil {
			return fmt.Errorf("Go build failed: %w\n%s", err, data)
		}
		return nil
	}
	for _, layer := range layers {
		if layer.manifest.Go == nil {
			continue
		}
		if err = run("build", "-mod=mod", "-modfile="+modFile, "-buildmode=archive", "-o", filepath.Join(build, layer.manifest.ID+".a"), layer.manifest.Go.Package); err != nil {
			return err
		}
	}
	stage, err := os.MkdirTemp(build, "linked-*")
	if err != nil {
		return err
	}
	for _, target := range []string{"server", "client", "modtool"} {
		if err = run("build", "-mod=mod", "-modfile="+modFile, "-trimpath", "-o", filepath.Join(stage, target+".exe"), "./cmd/"+target); err != nil {
			return err
		}
	}
	// Publish only after all three programs have compiled; old copies are kept.
	if err = os.MkdirAll(out, 0755); err != nil {
		return err
	}
	generation, err := os.MkdirTemp(out, "generation-*")
	if err != nil {
		return err
	}
	for _, target := range []string{"server", "client", "modtool"} {
		data, err := os.ReadFile(filepath.Join(stage, target+".exe"))
		if err != nil {
			return err
		}
		if err = atomicFile(filepath.Join(generation, target+".exe"), data); err != nil {
			return err
		}
	}
	if err = atomicFile(filepath.Join(generation, "registration.go.txt"), []byte(code)); err != nil {
		return err
	}
	storePath, err := filepath.Abs(store)
	if err != nil {
		return err
	}
	combinationPath, err := filepath.Abs(lockPath)
	if err != nil {
		return err
	}
	launch, err := json.MarshalIndent(native.LaunchConfig{ModRoot: storePath, Combination: combinationPath, Source: root}, "", "  ")
	if err != nil {
		return err
	}
	if err = atomicFile(filepath.Join(generation, "launch.json"), launch); err != nil {
		return err
	}
	absolute, err := filepath.Abs(generation)
	if err != nil {
		return err
	}
	data, err := json.Marshal(struct {
		Directory string    `json:"directory"`
		Lock      mods.Lock `json:"lock"`
	}{absolute, lock})
	if err != nil {
		return err
	}
	return atomicFile(filepath.Join(out, "active.json"), data)
}

func copyHostSource(root, target string) error {
	for _, name := range []string{"cmd", "internal", "pkg", "sdk", "content", "locales", "go.mod", "go.sum"} {
		err := fs.WalkDir(os.DirFS(root), name, func(path string, entry fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if entry.Type()&fs.ModeSymlink != 0 {
				return fmt.Errorf("host source symlink: %s", path)
			}
			if entry.IsDir() {
				return nil
			}
			if !entry.Type().IsRegular() {
				return fmt.Errorf("host source must be regular: %s", path)
			}
			if strings.HasSuffix(path, "_test.go") || path == "internal/native/generated.go" {
				return nil
			}
			data, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(path)))
			if err != nil {
				return err
			}
			return atomicFile(filepath.Join(target, filepath.FromSlash(path)), data)
		})
		if err != nil {
			return err
		}
	}
	return nil
}
